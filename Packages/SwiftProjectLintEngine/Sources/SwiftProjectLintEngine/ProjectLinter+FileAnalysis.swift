import Foundation
import SwiftParser
import SwiftProjectLintConfig
import SwiftProjectLintModels
import SwiftProjectLintRegistry
import SwiftProjectLintVisitors
import SwiftSyntax

extension ProjectLinter {

    /// Phrases that mark a file header as machine-written. Matched case-insensitively.
    ///
    /// `Code generated` and `DO NOT EDIT` are the Go and protobuf conventions and were the
    /// original two. They miss the commonest Swift spelling: Apple's FHIRModels writes
    /// *"Generated from FHIR 4.0.1-…"*, and 3,280 of its files carry it. Scanning it produced
    /// 1,155 Parallel List Drift findings, every one a synthesised `CodingKeys` enum — 89% of
    /// that rule's findings across a 1.8-million-line corpus, from one repository nobody
    /// hand-wrote.
    private static let generatedHeaderMarkers = [
        "do not edit",
        "code generated",
        "generated from",
        "generated by",
        "auto-generated",
        "autogenerated",
        "this file was automatically generated",
    ]

    /// Returns true if the file at the given path is machine-generated and should be skipped.
    ///
    /// Detection heuristics (any one suffices):
    /// - File suffix: `.pb.swift` (protobuf), `.generated.swift`
    /// - Header comment: the first 5 lines contain one of ``generatedHeaderMarkers``
    ///
    /// The five-line window is unchanged and deliberately so — `GeneratedFileDetectionTests`
    /// pins it, and widening it would start skipping hand-written files whose sixth line
    /// happens to mention code generation. FHIRModels needed no widening: its marker is on
    /// line 5. Only the vocabulary was short.
    ///
    /// The read is 1 KB rather than 512 bytes so that five *long* header lines still fit; that
    /// changes how much is read, not which lines count.
    static func isGeneratedFile(at filePath: String) -> Bool {
        let name = PathString.lastComponent(of: filePath)
        if name.hasSuffix(".pb.swift") || name.hasSuffix(".generated.swift") {
            return true
        }
        guard let handle = FileHandle(forReadingAtPath: filePath) else { return false }
        let data = handle.readData(ofLength: 1_024)
        guard let header = String(bytes: data, encoding: .utf8) else { return false }
        let firstLines = header
            .components(separatedBy: .newlines)
            .prefix(5)
            .joined(separator: "\n")
            .lowercased()
        return generatedHeaderMarkers.contains { firstLines.contains($0) }
    }

    /// Walks every tree with a fresh `TypeCollectorProtocol`-conforming visitor and returns the
    /// union of collected type names.
    ///
    /// The trees are the run's shared parse, so the pre-scan's name-set collectors read no file
    /// and parse nothing. This took a list of paths and read and parsed each file once per
    /// collector — seventeen parses per file before per-file analysis could start. The result is
    /// a union, so the order of `trees` does not matter.
    static func collectTypes<T: TypeCollectorProtocol>(
        _ _: T.Type, in trees: [SourceFileSyntax]
    ) -> Set<String> {
        var allTypes: Set<String> = []
        for tree in trees {
            let collector = T()
            collector.walk(tree)
            allTypes.formUnion(collector.collectedTypes)
        }
        return allTypes
    }

    /// Parses every project file once, for the pre-scan passes that need whole bodies rather than
    /// declaration names — `CleanInstanceMethodCatalog`, which has to judge what each method reads.
    static func parseAll(_ filePaths: [String]) -> [SourceFileSyntax] {
        filePaths.compactMap { filePath in
            guard let content = try? String(contentsOfFile: filePath) else { return nil }
            return Parser.parse(source: content)
        }
    }

    /// Bundle of per-run analysis inputs shared across every file in a
    /// task-group invocation. Existing only so concurrent task closures
    /// can capture a single value instead of ten.
    struct FileAnalysisEnvironment: Sendable {
        let projectRoot: String
        let registry: PatternVisitorRegistry
        let categories: [PatternCategory]?
        let ruleIdentifiers: [RuleIdentifier]?
        let identifiableTypes: Set<String>
        let identifiableCollectionProperties: Set<String>
        /// `View` names reading `@Environment(SomeType.self)`; `nil` when no pre-scan ran.
        let observableEnvironmentViews: Set<String>
        let inspectedTypeNames: Set<String>?
        let functionTypeAliases: Set<String>
        let spiMembers: Set<String>
        let underscoredMembers: Set<String>
        let enumTypes: Set<String>
        let actorTypes: ActorTypeCatalog
        let localTypes: Set<String>
        let observableTypes: Set<String>
        let protocolTypes: Set<String>
        let equatableTypes: Set<String>
        let valueTypes: Set<String>

        /// Functions this project declares — lets the Pure Closure rule tell a closure that still
        /// hides logic from one merely forwarding to a function the reader already extracted.
        let projectFunctions: Set<String>
        /// Base names of every `mutating func` — lets Actor Reentrancy see a project-defined gate
        /// update as a write.
        let mutatingMethods: Set<String>
        /// The one-hop callee join, resolved once in the pre-scan. See `PackagePurityJoin`.
        let impurePackageFunctions: ImpurePackageFunctions

        /// Types whose initialiser has defaulted parameters — the gate for `lossyStructRebuild`.
        let defaultedInitializerTypes: Set<String>

        /// Per type, the member names its `extension` blocks declare — the pre-scan's answer to
        /// "is part of this type in another file?". See `ExtensionMemberCatalog`.
        let extensionMembers: ExtensionMemberCatalog
        let closureWrapperTypes: ClosureWrapperTypeCatalog
        let equatableRemedies: EquatableRemedyCatalog
        let cleanInstanceMethods: CleanInstanceMethodCatalog

        /// Which framework allowlists the heuristic effect inferrer applies. `nil` means all of
        /// them, which is also the visitor's default — so this being dropped was invisible until
        /// somebody set it.
        let enabledFrameworkAllowlists: Set<String>?
        let layerPolicies: [LayerPolicy]

        /// The run's one parse, by discovery path — the trees the package purity was built from.
        /// A file analysed from here is judged on the tree the facts know, not on a re-parse.
        let shared: [String: SharedSource]
    }

    /// One analysed file: what it is, what it reported, and the tree it was judged on.
    struct AnalyzedFile: Sendable {
        let file: ProjectFile
        let issues: [LintIssue]
        let parsedAST: SourceFileSyntax
    }

    /// Convenience wrapper around `analyzeFile(at:projectRoot:...)` that
    /// pulls per-run inputs from a `FileAnalysisEnvironment`.
    static func analyzeFile(
        at filePath: String,
        env: FileAnalysisEnvironment
    ) -> AnalyzedFile? {
        analyzeFile(
            at: filePath,
            projectRoot: env.projectRoot,
            registry: env.registry,
            categories: env.categories,
            ruleIdentifiers: env.ruleIdentifiers,
            identifiableTypes: env.identifiableTypes,
            identifiableCollectionProperties: env.identifiableCollectionProperties,
            observableEnvironmentViews: env.observableEnvironmentViews,
            inspectedTypeNames: env.inspectedTypeNames,
            functionTypeAliases: env.functionTypeAliases,
            spiMembers: env.spiMembers,
            underscoredMembers: env.underscoredMembers,
            enumTypes: env.enumTypes,
            actorTypes: env.actorTypes,
            localTypes: env.localTypes,
            observableTypes: env.observableTypes,
            protocolTypes: env.protocolTypes,
            equatableTypes: env.equatableTypes,
            valueTypes: env.valueTypes,
            projectFunctions: env.projectFunctions,
            mutatingMethods: env.mutatingMethods,
            impurePackageFunctions: env.impurePackageFunctions,
            defaultedInitializerTypes: env.defaultedInitializerTypes,
            extensionMembers: env.extensionMembers,
            closureWrapperTypes: env.closureWrapperTypes,
            equatableRemedies: env.equatableRemedies,
            cleanInstanceMethods: env.cleanInstanceMethods,
            enabledFrameworkAllowlists: env.enabledFrameworkAllowlists,
            layerPolicies: env.layerPolicies,
            shared: env.shared[filePath]
        )
    }

    /// Analyzes a single file — pure function safe for concurrent task group use.
    static func analyzeFile(
        at filePath: String,
        projectRoot: String,
        registry: PatternVisitorRegistry,
        categories: [PatternCategory]?,
        ruleIdentifiers: [RuleIdentifier]?,
        identifiableTypes: Set<String> = [],
        identifiableCollectionProperties: Set<String> = [],
        observableEnvironmentViews: Set<String>? = nil,
        inspectedTypeNames: Set<String>? = nil,
        functionTypeAliases: Set<String> = [],
        spiMembers: Set<String> = [],
        underscoredMembers: Set<String> = [],
        enumTypes: Set<String> = [],
        actorTypes: ActorTypeCatalog = .empty,
        localTypes: Set<String> = [],
        observableTypes: Set<String> = [],
        protocolTypes: Set<String> = [],
        equatableTypes: Set<String> = [],
        valueTypes: Set<String> = [],
        projectFunctions: Set<String> = [],
        mutatingMethods: Set<String> = [],
        impurePackageFunctions: ImpurePackageFunctions = .empty,
        defaultedInitializerTypes: Set<String> = [],
        extensionMembers: ExtensionMemberCatalog = .empty,
        closureWrapperTypes: ClosureWrapperTypeCatalog = .empty,
        equatableRemedies: EquatableRemedyCatalog = .empty,
        cleanInstanceMethods: CleanInstanceMethodCatalog = .empty,
        enabledFrameworkAllowlists: Set<String>? = nil,
        layerPolicies: [LayerPolicy] = [],
        shared: SharedSource? = nil
    ) -> AnalyzedFile? {
        guard !Task.isCancelled else { return nil }
        guard let content = shared?.content ?? (try? String(contentsOfFile: filePath)) else { return nil }

        let relativePath = Self.relativePath(for: filePath, projectRoot: projectRoot)

        let file = ProjectFile(
            name: PathString.lastComponent(of: filePath),
            content: content,
            relativePath: relativePath
        )
        let parsedAST = shared?.tree ?? Parser.parse(source: content)
        let det = SourcePatternDetector(registry: registry)
        det.knownIdentifiableTypes = identifiableTypes
        det.knownIdentifiableCollectionProperties = identifiableCollectionProperties
        det.knownObservableEnvironmentViews = observableEnvironmentViews
        det.knownInspectedTypeNames = inspectedTypeNames
        det.knownFunctionTypeAliases = functionTypeAliases
        det.knownSPIMembers = spiMembers
        det.knownUnderscoredMembers = underscoredMembers
        det.knownEnumTypes = enumTypes
        det.knownActorTypes = actorTypes
        det.knownLocalTypeNames = localTypes
        det.knownObservableTypes = observableTypes
        det.knownProtocolTypes = protocolTypes
        det.knownEquatableTypes = equatableTypes
        det.knownValueTypes = valueTypes
        det.knownProjectFunctions = projectFunctions
        det.knownMutatingMethods = mutatingMethods
        det.knownImpurePackageFunctions = impurePackageFunctions
        det.knownDefaultedInitializerTypes = defaultedInitializerTypes
        det.knownExtensionMembers = extensionMembers
        det.knownClosureWrapperTypes = closureWrapperTypes
        det.knownEquatableRemedies = equatableRemedies
        det.knownCleanInstanceMethods = cleanInstanceMethods
        det.enabledFrameworkAllowlists = enabledFrameworkAllowlists
        det.layerPolicies = layerPolicies

        let rawIssues: [LintIssue]
        if let ruleIdentifiers {
            rawIssues = det.detectPatterns(
                in: file.content, filePath: file.relativePath,
                ruleIdentifiers: ruleIdentifiers, parsedAST: parsedAST
            )
        } else {
            rawIssues = det.detectPatterns(
                in: file.content, filePath: file.relativePath,
                categories: categories, parsedAST: parsedAST
            )
        }

        let issues = InlineSuppressionFilter.filter(rawIssues, fileContent: content)
        return AnalyzedFile(file: file, issues: issues, parsedAST: parsedAST)
    }

    /// Project-root-relative path for `filePath`, resolving symlinks on both sides so
    /// the prefix drop matches the canonicalized root (e.g. `/var` → `/private/var` on
    /// macOS). Falls back to the full resolved path when the file lies outside the
    /// declared root — keeps downstream relative-path dedup keys unique.
    static func relativePath(for filePath: String, projectRoot: String) -> String {
        let resolvedRoot = URL(fileURLWithPath: projectRoot).resolvingSymlinksInPath().path
        let resolvedFile = URL(fileURLWithPath: filePath).resolvingSymlinksInPath().path
        let prefix = resolvedRoot.hasSuffix("/") ? resolvedRoot : resolvedRoot + "/"
        guard resolvedFile.hasPrefix(prefix) else { return resolvedFile }
        return String(resolvedFile.dropFirst(prefix.count))
    }

    /// Reads and parses evidence-only files into `(ProjectFile, AST)` pairs *without*
    /// running per-file detection: they contribute to the cross-file walk but cannot
    /// produce reported issues (see the call site for why exclusion is a reporting
    /// filter, not an evidence filter). Unreadable files are skipped.
    ///
    /// A file in `sources` — the run's shared parse — is taken from there, so the cross-file walk
    /// sees the same tree the package purity was built from.
    static func parseEvidenceFiles(
        at filePaths: [String],
        projectRoot: String,
        sources: [String: SharedSource] = [:]
    ) -> [(file: ProjectFile, ast: SourceFileSyntax)] {
        filePaths.compactMap { filePath in
            let source = sources[filePath]
            guard let content = source?.content ?? (try? String(contentsOfFile: filePath)) else { return nil }
            let file = ProjectFile(
                name: PathString.lastComponent(of: filePath),
                content: content,
                relativePath: Self.relativePath(for: filePath, projectRoot: projectRoot)
            )
            return (file: file, ast: source?.tree ?? Parser.parse(source: content))
        }
    }

    /// Applies inline-suppression filtering to cross-file issues. Grouped
    /// by the issue's primary file (`LintIssue.filePath` — the first
    /// location) and filtered against that file's content. Issues whose
    /// primary file is not in the project-files set (defensive — shouldn't
    /// normally happen) pass through unfiltered so no diagnostic goes
    /// missing.
    ///
    /// Per-file issues are already filtered inside `analyzeFile`. Cross-
    /// file issues are emitted by `CrossFileAnalysisEngine` and
    /// previously bypassed suppression entirely; this method closes that
    /// gap so `// swiftprojectlint:disable*` comments work equivalently
    /// for both rule kinds.
    static func applyInlineSuppression(
        to crossFileIssues: [LintIssue],
        files: [ProjectFile]
    ) -> [LintIssue] {
        guard !crossFileIssues.isEmpty else { return crossFileIssues }

        // Defensive: duplicate relativePaths shouldn't crash inline suppression
        // dedup (e.g., an edge case where resolution still collides on symlinks
        // or on-disk duplicates). Keep first occurrence.
        let contentByRelativePath = Dictionary(files.map { ($0.relativePath, $0.content) }) { first, _ in
            first
        }

        let grouped = Dictionary(grouping: crossFileIssues) { $0.filePath }
        var filtered: [LintIssue] = []
        filtered.reserveCapacity(crossFileIssues.count)

        for (filePath, issuesInFile) in grouped {
            guard let content = contentByRelativePath[filePath] else {
                filtered.append(contentsOf: issuesInFile)
                continue
            }
            filtered.append(contentsOf: InlineSuppressionFilter.filter(
                issuesInFile,
                fileContent: content
            ))
        }

        return filtered
    }
}
